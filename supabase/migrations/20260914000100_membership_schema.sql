UPDATE public.members SET x_follower_count = 0 WHERE x_follower_count IS NULL;
UPDATE public.members SET points = 0 WHERE points IS NULL;
UPDATE public.members SET tier = 'member' WHERE tier IS NULL;
UPDATE public.members SET referral_chain_depth = 0 WHERE referral_chain_depth IS NULL;
UPDATE public.members SET network_size = 0 WHERE network_size IS NULL;
UPDATE public.members SET multiplier = 1.0 WHERE multiplier IS NULL;
UPDATE public.members SET login_streak = 0 WHERE login_streak IS NULL;
UPDATE public.members SET confirmed_email = false WHERE confirmed_email IS NULL;
UPDATE public.members SET is_og = false WHERE is_og IS NULL;
UPDATE public.members SET
  x_follower_count = greatest(x_follower_count, 0),
  points = greatest(points, 0),
  referral_chain_depth = greatest(referral_chain_depth, 0),
  network_size = greatest(network_size, 0),
  login_streak = greatest(login_streak, 0);
UPDATE public.members SET multiplier = CASE
  WHEN network_size >= 200 THEN 3.0
  WHEN network_size >= 51 THEN 2.0
  WHEN network_size >= 11 THEN 1.5
  ELSE 1.0
END;

