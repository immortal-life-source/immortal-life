CREATE TABLE IF NOT EXISTS public.members (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz DEFAULT now() NOT NULL,
  x_id text NOT NULL,
  x_username text NOT NULL,
  x_display_name text NOT NULL,
  x_avatar_url text,
  x_follower_count integer DEFAULT 0 NOT NULL,
  points integer DEFAULT 0 NOT NULL,
  tier text DEFAULT 'member' NOT NULL,
  invited_by bigint,
  referral_chain_depth integer DEFAULT 0 NOT NULL,
  network_size integer DEFAULT 0 NOT NULL,
  multiplier numeric(3,1) DEFAULT 1.0 NOT NULL,
  last_login timestamptz DEFAULT now(),
  last_daily_claim timestamptz,
  login_streak integer DEFAULT 0 NOT NULL,
  confirmed_email boolean DEFAULT false NOT NULL,
  is_og boolean DEFAULT false NOT NULL
);

